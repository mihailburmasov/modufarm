function f(string $type, string $bind, string $label, string $hint = '', array $o = []): array
{
    return ['type' => $type, 'bind' => $bind, 'label' => $label, 'hint' => $hint] + $o;
}
function k(string $type, string $key, string $label, string $hint = '', array $o = []): array
{
    return ['type' => $type, 'key' => $key, 'label' => $label, 'hint' => $hint] + $o;
}
function head(string $title, string $note = ''): array { return ['type' => 'head', 'label' => $title, 'hint' => $note]; }

const TOPIC_HINT = 'Какая тема отметится в форме заявки, если нажать кнопку. Должна дословно совпадать с одной из тем в разделе «Заявка и контакты»';

function title_fields(string $p, bool $lead = true): array
{
    $out = [
        f('text', $p . 'eyebrow', 'Надзаголовок', 'Мелкая строка над заголовком'),
        f('textarea', $p . 'title', 'Заголовок раздела', '', ['rows' => 2, 'required' => true]),
    ];
    if ($lead) $out[] = f('textarea', $p . 'lead', 'Текст под заголовком', '', ['rows' => 3]);
    return $out;
}
function hide_field(string $p): array { return f('bool', $p . 'hidden', 'Скрыть раздел с сайта', 'Раздел и пункты меню, которые на него ведут, пропадут с сайта. Тексты сохранятся.'); }
function button_fields(string $p, string $label = 'Кнопка'): array
{
    return [
        f('text', $p . 'btnLabel', $label . ': надпись', '', ['required' => true]),
        f('text', $p . 'btnTopic', $label . ': тема заявки', TOPIC_HINT),
    ];
}

