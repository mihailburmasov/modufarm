// Все поля раздела в плоском виде (для проверки, что сохраняется только разрешённое)
function schema_binds(array $fields): array
{
    $out = [];
    foreach ($fields as $fd) if (!empty($fd['bind'])) $out[$fd['bind']] = $fd;
    return $out;
}
